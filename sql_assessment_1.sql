-- 38. Channels whose total sales amount is greater than 100000
SELECT CHANNEL_ID, SUM(AMOUNT_SOLD) AS TOTAL_SALES FROM SH.SALES GROUP BY CHANNEL_ID HAVING SUM(AMOUNT_SOLD) > 100000;

-- 39. Promotion categories whose average promotion cost is greater than 1000
SELECT PROMO_CATEGORY, AVG(PROMO_COST) AS AVG_PROMOTION_COST FROM SH.PROMOTIONS GROUP BY PROMO_CATEGORY HAVING AVG(PROMO_COST) > 1000;

