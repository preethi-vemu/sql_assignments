-- ## GROUP BY – DIFFERENT BUSINESS QUESTIONS


-- 16. Number of customers belonging to each marital status
SELECT CUST_MARITAL_STATUS, COUNT(*) AS CUSTOMER_COUNT FROM SH.CUSTOMERS GROUP BY CUST_MARITAL_STATUS;

-- 17. Average customer year of birth for each gender
SELECT CUST_GENDER, AVG(CUST_YEAR_OF_BIRTH) AS AVG_YEAR_OF_BIRTH FROM SH.CUSTOMERS GROUP BY CUST_GENDER;

-- 18. Average list price of products in each product category
SELECT PROD_CATEGORY, AVG(PROD_LIST_PRICE) AS AVG_LIST_PRICE FROM SH.PRODUCTS GROUP BY PROD_CATEGORY;

-- 19. Highest minimum price in each product subcategory
SELECT PROD_SUBCATEGORY, MAX(PROD_MIN_PRICE) AS Highest_MIN_PRICE FROM SH.PRODUCTS GROUP BY PROD_SUBCATEGORY;

-- 20. Total sales amount generated by each channel
SELECT CHANNEL_ID, SUM(AMOUNT_SOLD) AS TOTAL_SALES FROM SH.SALES GROUP BY CHANNEL_ID;

-- 21. Total quantity sold for each product
SELECT PROD_ID, SUM(QUANTITY_SOLD) AS TOTAL_QUANTITY_SOLD FROM SH.SALES GROUP BY PROD_ID;

-- 22. Average sales amount for each promotion
SELECT PROMO_ID, AVG(AMOUNT_SOLD) AS AVG_SALES_AMOUNT FROM SH.SALES GROUP BY PROMO_ID;

-- 23. Total promotion cost for each promotion category
SELECT PROMO_CATEGORY, SUM(PROMO_COST) AS TOTAL_PROMOTION_COST FROM SH.PROMOTIONS GROUP BY PROMO_CATEGORY;

-- 24. Number of countries belonging to each region
SELECT COUNTRY_REGION_ID, COUNT(*) AS COUNTRY_COUNT FROM SH.COUNTRIES GROUP BY COUNTRY_REGION_ID;

-- 25. Average unit cost for each product
SELECT PROD_ID, AVG(UNIT_COST) AS AVG_UNIT_COST FROM SH.COSTS GROUP BY PROD_ID;

-- ## TWO-LEVEL GROUP BY

-- 26. Count customers by gender and marital status
SELECT CUST_GENDER, CUST_MARITAL_STATUS, COUNT(*) AS CUSTOMER_COUNT FROM SH.CUSTOMERS GROUP BY CUST_GENDER, CUST_MARITAL_STATUS;

-- 27. Count products by product category and product subcategory
SELECT PROD_CATEGORY, PROD_SUBCATEGORY, COUNT(*) AS PRODUCT_COUNT FROM SH.PRODUCTS GROUP BY PROD_CATEGORY, PROD_SUBCATEGORY;

-- 28. Calculate total sales amount for each product and channel combination
SELECT PROD_ID, CHANNEL_ID, SUM(AMOUNT_SOLD) AS TOTAL_SALES FROM SH.SALES GROUP BY PROD_ID, CHANNEL_ID;

-- 29. Calculate total quantity sold for each channel and promotion combination
SELECT CHANNEL_ID, PROMO_ID, SUM(QUANTITY_SOLD) AS TOTAL_QUANTITY_SOLD FROM SH.SALES GROUP BY CHANNEL_ID, PROMO_ID;

-- 30. Find the average unit cost for each product and promotion combination
SELECT PROD_ID, PROMO_ID, AVG(UNIT_COST) AS AVG_UNIT_COST FROM SH.COSTS GROUP BY PROD_ID, PROMO_ID;

-- ## WHERE + GROUP BY

-- 31. Total sales amount for each channel where AMOUNT_SOLD > 500
SELECT CHANNEL_ID, SUM(AMOUNT_SOLD) AS TOTAL_SALES FROM SH.SALES WHERE AMOUNT_SOLD > 500 GROUP BY CHANNEL_ID;

-- 32. Average list price for each product category where list price > 100
SELECT PROD_CATEGORY, AVG(PROD_LIST_PRICE) AS AVG_LIST_PRICE FROM SH.PRODUCTS WHERE PROD_LIST_PRICE > 100 GROUP BY PROD_CATEGORY;

-- 33. Count customers by marital status for customers born after 1970
SELECT CUST_MARITAL_STATUS, COUNT(*) AS CUSTOMER_COUNT FROM SH.CUSTOMERS WHERE CUST_YEAR_OF_BIRTH > 1970 GROUP BY CUST_MARITAL_STATUS;

-- 34. Average promotion cost for each promotion category where cost > 500
SELECT PROMO_CATEGORY, AVG(PROMO_COST) AS AVG_PROMOTION_COST FROM SH.PROMOTIONS WHERE PROMO_COST > 500 GROUP BY PROMO_CATEGORY;

-- 35. Maximum unit price for each product where unit cost > 50
SELECT PROD_ID, MAX(UNIT_PRICE) AS MAX_UNIT_PRICE FROM SH.COSTS WHERE UNIT_COST > 50 GROUP BY PROD_ID;

-- 36. Marital statuses having more than 100 customers
SELECT CUST_MARITAL_STATUS, COUNT(*) AS CUSTOMER_COUNT FROM SH.CUSTOMERS GROUP BY CUST_MARITAL_STATUS HAVING COUNT(*) > 100;

-- 37. Product categories whose average list price is greater than 500
